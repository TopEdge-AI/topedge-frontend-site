/** Catalog rows for one festival, in send order. */
const STAGE_ORDER: FestivalStageId[] = ['early-access', 'gift-guide', 'flash-sale', 'greeting'];

export function catalogRowsForFestival(festivalName: string): FestivalCatalogRow[] {
  return FESTIVAL_CATALOG.filter((r) => r.festivalName === festivalName).sort(
    (a, b) => STAGE_ORDER.indexOf(a.stage) - STAGE_ORDER.indexOf(b.stage),
  );
}
