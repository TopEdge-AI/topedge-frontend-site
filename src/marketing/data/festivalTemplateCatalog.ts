/**
 * The festive template catalog, vendored from the product.
 *
 * Source of truth: `src/config/festivalMarketingCatalog.js` in the dashboard
 * repo, itself generated from `public/SaaS_ festive camp lists - V1.csv`. Every
 * body, button label and footer below is copied verbatim, because the whole
 * point of publishing them is that a merchant sees on the website exactly the
 * words the dashboard will hand them. Do not "improve" the copy here — change
 * it in the dashboard catalog and re-vendor, or the two drift and the page
 * starts lying about the product.
 *
 * 25 festivals x 4 campaign stages = 100 templates.
 *
 * What the catalog deliberately does NOT carry: a header component. Meta
 * reviews festive marketing templates more tightly than order updates, and a
 * media header is the most common reason one comes back rejected, so these
 * ship as body + footer + button. A merchant who wants festive creative adds
 * it on their own submission.
 */

